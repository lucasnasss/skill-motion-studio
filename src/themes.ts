export const resolveTheme = (project: MotionProject): ThemeTokens => {
  const base = THEMES[project.theme] ?? THEMES.minimal;
  return {
    ...base,
    ...project.palette,
    titleFont: project.typography?.titleFont ?? base.titleFont,
    bodyFont: project.typography?.bodyFont ?? base.bodyFont,
    titleWeight: project.typography?.titleWeight ?? base.titleWeight,
    bodyWeight: project.typography?.bodyWeight ?? base.bodyWeight,
  };
};

